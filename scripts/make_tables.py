"""Collect every result on Drive into paper-ready Markdown tables (RESULTS.md) + results.json.

    python scripts/make_tables.py --govi "G:/My Drive/govi-ai" --out docs/results

Missing experiments are shown as "pending", so this can be run at any time.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

CROPS = ("rice", "tea", "chili")
LEVELS = ("unknown_disease", "other_crops", "other_plant", "non_plant")


def load(p: Path):
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def f(v, nd=3):
    return "–" if v is None else (f"{v:.{nd}f}" if isinstance(v, float) else str(v))


def table(header: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(f(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def g(d, *keys):
    for k in keys:
        if not isinstance(d, dict) or k not in d:
            return None
        d = d[k]
    return d


def crop_cells(rep: dict, crop: str, score: str = "mahalanobis") -> list:
    c = g(rep, "crops", crop) or {}
    return [g(c, "closed_set", "macro_f1"), g(c, "closed_set", "ece_calibrated"),
            *[g(c, "open_set", lvl, score, "auroc") for lvl in LEVELS]]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--govi", type=Path, required=True)
    ap.add_argument("--out", type=Path, default=Path("docs/results"))
    ap.add_argument("--extra-runs", type=Path, nargs="*", default=[],
                    help="more runs/ folders (team members' results); missing folders are skipped")
    args = ap.parse_args()
    G = args.govi
    args.out.mkdir(parents=True, exist_ok=True)
    md, js = ["# Results (auto-generated by scripts/make_tables.py)\n"], {}

    # ---- dataset
    br = load(G / "dataset_report.json") or load(G / "artifacts" / "build_report.json")
    if br:
        d = br["dedupe"]
        md += ["## Dataset", table(["images collected", "kept", "duplicates removed", "label conflicts dropped", "train", "val", "test", "unknown-disease"],
                                   [[d["images_in"], d["images_kept"], d["duplicate_images"], d["conflict_images_dropped"],
                                     br["by_split"].get("train"), br["by_split"].get("val"), br["by_split"].get("test"),
                                     br["by_split"].get("unknown_eval")]]), ""]
        js["dataset"] = {"dedupe": d, "by_split": br["by_split"]}

    # ---- v1 baseline
    lb = load(G / "artifacts" / "legacy_baseline.json")
    if lb:
        rows = [[c, g(lb, c, "closed_set", "accuracy"), g(lb, c, "closed_set", "macro_f1"), g(lb, c, "unsupported_share"),
                 *[g(lb, c, "open_set_msp", lvl, "auroc") for lvl in LEVELS]] for c in CROPS]
        md += ["## Govi Isuru v1 (legacy) on the new test sets",
               table(["crop", "accuracy", "macro-F1", "classes it cannot output", *[f"AUROC {l}" for l in LEVELS]], rows), ""]
        js["legacy"] = lb

    # ---- probes
    probes = sorted((G / "features" / "results").glob("probe_*.json")) if (G / "features" / "results").exists() else []
    if probes:
        rows = []
        for p in probes:
            r = load(p) or {}
            name = "+".join(r.get("backbones", [p.stem]))
            for c in CROPS:
                protos = g(r, "crops", c) or {}
                ind = protos.get("split", {})
                lodo = [v for k, v in protos.items() if k.startswith("lodo_") and "closed_set" in v]
                rows.append([name, c, g(ind, "closed_set", "macro_f1"),
                             sum(g(v, "closed_set", "macro_f1") for v in lodo) / len(lodo) if lodo else None,
                             g(ind, "open_set", "unknown_disease", "energy", "auroc"),
                             g(ind, "open_set", "unknown_disease", "mahalanobis", "auroc")])
        md += ["## Frozen-backbone linear probes (teacher candidates and baselines)",
               table(["backbone", "crop", "macro-F1 in-domain", "macro-F1 LODO mean", "AUROC unknown (energy)",
                      "AUROC unknown (Mahalanobis)"], rows), ""]
        js["probes"] = rows

    # ---- student runs
    run_dirs = [d for root in [G / "runs", *args.extra_runs] if root.exists() for d in sorted(root.iterdir()) if d.is_dir()]
    reps = {}
    for d in run_dirs:  # the first finished copy of a run wins (owner's folder first)
        if d.name not in reps or reps[d.name][0] is None:
            reps[d.name] = (load(d / "report.json"), load(d / "report_clean.json"))
    main_run = reps.get("mnv4_s_split", (None, None))
    if main_run[0]:
        rows = [[c, *crop_cells(main_run[0], c)] for c in CROPS]
        md += ["## Student (MobileNetV4-S, distilled), in-domain test",
               table(["crop", "macro-F1", "ECE", *[f"AUROC {l}" for l in LEVELS]], rows), ""]
        gate = main_run[0].get("gate", {})
        md += [table(["gate macro-F1", "wrong-crop rate", "false-reject rate", "unknown routed to right crop"],
                     [[gate.get("macro_f1"), gate.get("wrong_crop_rate"), gate.get("false_reject_rate"),
                       gate.get("unknown_disease_right_crop")]]), ""]
    if main_run[1]:
        rows = [[c, *crop_cells(main_run[1], c)] for c in CROPS]
        md += [f"### Same, near-duplicate-free test subset ({main_run[1].get('excluded_near_duplicates')} test rows removed)",
               table(["crop", "macro-F1", "ECE", *[f"AUROC {l}" for l in LEVELS]], rows), ""]

    abl = {"full": "mnv4_s_split", "no KD": "abl_no_kd", "no outlier exposure": "abl_no_oe", "no margin": "abl_no_margin"}
    rows = []
    for label, run in abl.items():
        rep = (reps.get(run) or (None, None))[0]
        for c in CROPS:
            rows.append([label, c, *crop_cells(rep, c)] if rep else [label, c, "pending", None, None, None, None, None])
    md += ["## Ablations", table(["variant", "crop", "macro-F1", "ECE", *[f"AUROC {l}" for l in LEVELS]], rows), ""]

    rows = []
    for run, (rep, clean) in reps.items():
        if not run.startswith("lodo_") or not rep:
            continue
        held = rep.get("protocol", run).removeprefix("lodo_")
        for c in CROPS:
            cs = g(rep, "crops", c, "closed_set")
            if cs:
                rows.append([held, c, cs.get("macro_f1"), g(clean, "crops", c, "closed_set", "macro_f1"),
                             g(rep, "crops", c, "open_set", "unknown_disease", "mahalanobis", "auroc")])
    if rows:
        md += ["## Cross-dataset: leave-one-dataset-out (student)",
               table(["held-out source", "crop", "macro-F1", "macro-F1 near-dup-free", "AUROC unknown"], rows), ""]

    # ---- deployment, audit, officer loop, XAI
    bundle = load(G / "bundles" / "v2" / "bundle_report.json") or load(G / "bundles" / "v1" / "bundle_report.json")
    cal = (bundle or {}).get("calibration", {})
    rows = []
    for c, r in cal.items():
        if c == "gate" or not isinstance(r, dict):
            continue
        loco = r.get("novelty_loco_auroc_val") or {}
        rows.append([c, r.get("novelty_score", "mahalanobis"), loco.get("mahalanobis"), loco.get("msp"), loco.get("fused"),
                     r.get("test_unknown_auroc"), r.get("unknown_disease_detected"), r.get("test_known_flagged_unknown"),
                     r.get("test_coverage"), r.get("test_risk_on_accepted")])
    if rows:
        md += ["## Serving decisions (calibrated on validation; test shown)",
               table(["crop", "unknown score", "LOCO AUROC maha", "LOCO msp", "LOCO fused", "test AUROC unknown",
                      "unknowns caught", "known flagged unknown", "answered (coverage)", "error when answered"], rows),
               "", "Unknown score chosen per crop by leave-one-known-class-out AUROC on validation; unknown and test "
               "data are never used for any choice.", ""]
    if bundle:
        rows = [[k, g(bundle, k, "argmax_agreement", "gate"), g(bundle, k, "latency_ms_1thread", "p50"),
                 g(bundle, k, "latency_ms_1thread", "p95")] for k in ("model.onnx", "model.int8.onnx") if k in bundle]
        md += ["## Deployment (1 CPU thread)", table(["model", "gate argmax agreement vs PyTorch", "p50 ms", "p95 ms"], rows),
               f"Files: {bundle.get('files')}", ""]
    audit = load(G / "audit" / "summary.json")
    if audit:
        rows = [[p, v["n_test"], v["share_test_at_or_above"].get("0.95"), v["share_test_at_or_above"].get("0.99"),
                 v.get("median_test_max_sim")] for p, v in audit["protocols"].items()]
        md += [f"## Embedding near-duplicate audit ({audit['backbone']})",
               table(["protocol", "test images", "share cos >= 0.95", "share cos >= 0.99", "median max cos"], rows), ""]
    off = load(G / "officer" / "officer_loop.json")
    if off:
        rows = []
        for c, classes in off.get("few_shot", {}).items():
            for k in ("1", "5", "20"):
                vals = [v["shots"][k] for v in classes.values() if k in v["shots"]]
                if vals:
                    rows.append([c, k, sum(v["recall_new"] for v in vals) / len(vals),
                                 sum(v["false_accept_old_as_new"] for v in vals) / len(vals),
                                 sum(v["old_class_accuracy"] for v in vals) / len(vals)])
        md += ["## Officer loop: new disease from k confirmed photos (no retraining)",
               table(["crop", "k", "recall of new disease", "old classes taken as new", "old-class accuracy"], rows), ""]
        rows = [[c, v.get("recommended_threshold"),
                 g(v, "thresholds", str(v.get("recommended_threshold")), "purity"),
                 g(v, "thresholds", str(v.get("recommended_threshold")), "ari")]
                for c, v in off.get("clustering", {}).items() if "thresholds" in v]
        if rows:
            md += [table(["crop", "recommended cluster threshold", "purity", "ARI"], rows), ""]
    xai = load(G / "xai" / "faithfulness.json")
    if xai:
        rows = [[c, *[g(v, "deletion_auc_mean", m) for m in ("cam", "gradcam", "gradcam_pp", "random")]]
                for c, v in xai.get("crops", {}).items()]
        md += ["## Explanation faithfulness (deletion AUC, lower = more faithful)",
               table(["crop", "CAM (served)", "Grad-CAM", "Grad-CAM++", "random"], rows), ""]

    (args.out / "RESULTS.md").write_text("\n".join(md), encoding="utf-8")
    (args.out / "results.json").write_text(json.dumps(js, indent=1, default=str), encoding="utf-8")
    print(f"wrote {args.out / 'RESULTS.md'}")


if __name__ == "__main__":
    main()
